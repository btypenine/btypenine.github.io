const ns = s => String(s || '').replace(/\s/g, '');
const kwSet = s => String(s || '').split(/\s+/).filter(Boolean).map(ns).sort().join('|');

function judge(K, c) {
  const now = new Date(c.now);
  const why = [];
  let got;
  if (c.kind === 'reg') {
    const qq = K.parseQuery(c.s, now);
    if (qq) why.push('확인 질문으로 오판');
    const p = K.parse(c.s, now);
    got = `${p.date || '미정'} ${p.time || '--:--'}${p.end ? '~' + p.end : ''} 「${p.title}」${p.place ? ' @' + p.place : ''}`;
    if (p.date !== c.date) why.push(`날짜 ${p.date}≠${c.date}`);
    if (p.time !== c.time) why.push(`시간 ${p.time}≠${c.time}`);
    if ((p.end || null) !== c.end) why.push(`끝 ${p.end}≠${c.end}`);
    if (ns(p.place) !== ns(c.place)) why.push(`장소 「${p.place}」≠「${c.place}」`);
    if (ns(p.title) !== ns(c.title)) why.push(`제목 「${p.title}」≠「${c.title}」`);
  } else {
    const qq = K.parseQuery(c.s, now);
    if (!qq) { why.push('질문으로 인식 못함(등록됨)'); got = '등록으로 처리'; }
    else {
      got = `${qq.nodate ? '날짜미정' : (qq.from || '전체') + '~' + (qq.to || '')} 검색어「${qq.keyword}」`;
      if (!!qq.nodate !== c.nodate) why.push('날짜미정 여부 다름');
      if (qq.from !== c.from || qq.to !== c.to) {
        // 검색어만 있는 질문은 기간 없음이 기대값
        why.push(`기간 ${qq.from}~${qq.to}≠${c.from}~${c.to}`);
      }
      if (kwSet(qq.keyword) !== kwSet(c.kw)) why.push(`검색어 「${qq.keyword}」≠「${c.kw}」`);
    }
  }
  return { ok: !why.length, why, got };
}

function run(K, { all = false, quiet = false } = {}) {
  const res = CASES.map(c => ({ c, ...judge(K, c) }));
  const pass = res.filter(x => x.ok).length;
  const regP = res.filter(x => x.c.kind === 'reg' && x.ok).length;
  const qP = res.filter(x => x.c.kind === 'query' && x.ok).length;
  const exFail = res.filter(x => x.c.ex && !x.ok);
  const misQ = res.filter(x => x.c.kind === 'reg' && x.why.includes('확인 질문으로 오판'));
  if (!quiet) {
    console.log(`\n말로일정 해석기 시험 — 기준 ${NOW}`);
    for (const x of res) {
      if (x.ok && !all) continue;
      console.log(`${x.ok ? '✅' : '❌'} [${x.c.kind === 'reg' ? '등록' : '확인'}·${x.c.cat}${x.c.ex ? '·기존예시' : ''}] ${x.c.s}\n    → ${x.got}${x.ok ? '' : '\n    ✗ ' + x.why.join(' / ')}`);
    }
    console.log('\n──────── 결과 ────────');
    console.log(`전체   ${pass}/${CASES.length} (${(pass / CASES.length * 100).toFixed(1)}%)`);
    console.log(`등록   ${regP}/${R.length}`);
    console.log(`확인   ${qP}/${Q.length}`);
    console.log(`기존 예시 실패 ${exFail.length}건 · 등록→질문 오판 ${misQ.length}건`);
  }
  return { pass, total: CASES.length, rate: pass / CASES.length, exFail: exFail.length, misQ: misQ.length, res };
}

module.exports = { loadKoParse, CASES, run };

if (require.main === module) {
  const args = process.argv.slice(2);
  const file = args.find(a => !a.startsWith('--')) || path.join(__dirname, '..', 'index.html');
  const K = loadKoParse(file);
  const out = run(K, { all: args.includes('--all') });
  // 완료 기준: 95% 이상 + 기존 예시 전부 통과 + 오판 0
  const okAll = out.rate >= 0.95 && out.exFail === 0 && out.misQ === 0;
  console.log(okAll ? '완료 기준 충족 ✅' : '완료 기준 미달 ❌ (95% 이상·기존 예시 전부·오판 0)');
  process.exit(okAll ? 0 : 1);
}
