// ---------- 해석기 불러오기 ----------
function loadKoParse(file) {
  const html = fs.readFileSync(file, 'utf8');
  const start = html.indexOf('const KoParse = (() => {');
  if (start < 0) throw new Error('KoParse 블록을 찾지 못함: ' + file);
  const end = html.indexOf('\n})();', start);
  if (end < 0) throw new Error('KoParse 블록 끝을 찾지 못함');
  const code = html.slice(start, end + 6) + '\nthis.KoParse = KoParse;';
  const ctx = { Date, Math, String, Number, RegExp, Set, Map, Array, Object, JSON };
  vm.createContext(ctx);
  vm.runInContext(code, ctx);
  return ctx.KoParse;
}

